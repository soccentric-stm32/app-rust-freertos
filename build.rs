// build.rs - version and build metadata for the Rust crate
//
// Author: Sandesh Ghimire <sandesh@soccentric.com>
// SRS:    RFGEN-002
//
// The version comes from VERSION, the same file CMakeLists.txt reads for the
// BOOT image header.  FreeRTOS is provided by the STM32CubeF7 image, so its
// release is recorded here as a constant for the Hello/Status replies.

use std::process::Command;
use std::{
    env, fs,
    time::{SystemTime, UNIX_EPOCH},
};

const FREERTOS: &str = "FreeRTOS 10.2.0";

fn version() -> String {
    let text = fs::read_to_string("VERSION").expect("VERSION is readable");
    let field = |key: &str| {
        text.lines()
            .filter_map(|line| line.split_once('='))
            .find(|(k, _)| k.trim() == key)
            .map(|(_, v)| v.trim().to_owned())
            .unwrap_or_else(|| "0".to_owned())
    };
    format!(
        "{}.{}.{}",
        field("VERSION_MAJOR"),
        field("VERSION_MINOR"),
        field("PATCHLEVEL")
    )
}

fn command_output(program: &str, args: &[&str]) -> Option<String> {
    Command::new(program)
        .args(args)
        .output()
        .ok()
        .filter(|o| o.status.success())
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_owned())
        .filter(|s| !s.is_empty())
}

fn main() {
    println!("cargo:rerun-if-changed=VERSION");
    println!("cargo:rerun-if-changed=.git/HEAD");
    println!("cargo:rerun-if-env-changed=SOURCE_DATE_EPOCH");

    let version = version();
    let cargo_version = env::var("CARGO_PKG_VERSION").unwrap_or_default();
    assert_eq!(
        version, cargo_version,
        "VERSION and Cargo.toml disagree on the version"
    );

    let mut commit = command_output("git", &["rev-parse", "--short=12", "HEAD"])
        .unwrap_or_else(|| "unknown".to_owned());
    if command_output("git", &["status", "--porcelain"]).is_some() && commit != "unknown" {
        commit.push_str("-dirty");
    }

    let build_time = env::var("SOURCE_DATE_EPOCH")
        .ok()
        .and_then(|s| s.parse::<u64>().ok())
        .unwrap_or_else(|| {
            SystemTime::now()
                .duration_since(UNIX_EPOCH)
                .map(|d| d.as_secs())
                .unwrap_or(0)
        });
    let build_date = command_output(
        "date",
        &[
            "-u",
            "-d",
            &format!("@{}", build_time),
            "+%Y-%m-%dT%H:%M:%SZ",
        ],
    )
    .unwrap_or_else(|| build_time.to_string());

    let rustc = env::var("RUSTC").unwrap_or_else(|_| "rustc".to_owned());
    let rustc = command_output(&rustc, &["--version"])
        .and_then(|v| v.split_whitespace().nth(1).map(str::to_owned))
        .unwrap_or_else(|| "unknown".to_owned());

    let version_text = format!("{} (Rust {}, {})", version, rustc, FREERTOS);
    let out = env::var("OUT_DIR").expect("OUT_DIR is set by cargo");
    let version_rs = format!(
        "// Generated by build.rs. Do not edit.\n\
         pub const VERSION: &str = {:?};\n\
         pub const VERSION_TEXT: &str = {:?};\n\
         pub const GIT_COMMIT: &str = {:?};\n\
         pub const BUILD_TIME: &str = {:?};\n",
        version, version_text, commit, build_date,
    );
    fs::write(format!("{}/version.rs", out), version_rs).expect("version.rs is writable");
}
